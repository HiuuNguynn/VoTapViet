/** Chuyển văn bản Unicode thường sang chuỗi dùng glyph nối nét của HP001. */
export function noiNet(text: string): string {
  let s = " " + text + " ";
  for (const [from, to] of NOI_NET_PAIRS) s = s.split(from).join(to);
  return s.trim();
}
